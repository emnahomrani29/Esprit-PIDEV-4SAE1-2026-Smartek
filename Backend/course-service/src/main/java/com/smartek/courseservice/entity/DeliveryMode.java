package com.smartek.courseservice.entity;

/**
 * Enum représentant le mode de livraison d'un cours
 */
public enum DeliveryMode {
    /**
     * Cours en présentiel (dans une salle physique)
     */
    PRESENTIEL,
    
    /**
     * Cours en ligne (avec sessions live virtuelles)
     */
    EN_LIGNE
}
